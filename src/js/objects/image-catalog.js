const FAMILY_RULES = [
  [/burger/, 'meat'],
  [/ice-cream/, 'dairy'],
  [/cow|monkey|octopus|butterfly|dinosaur|goldfish|cat|peacock|frog|whale|shark|dragon|elephant|unicorn|jellyfish|penguin|turtle|fox|owl|horse|phoenix|duck|crab|leopard|lion|giraffe|hippo|rhino|zebra|panda|gorilla|chameleon/, 'animal'],
  [/tree|mountain|mushroom|volcano|flower|waterfall|cactus|reef|island|bonsai|cave|river|moon|garden|earth|cherry|rock|storm/, 'nature'],
  [/castle|stairs|door|tower|bridge|lighthouse|gate|palace|pavilion|treehouse|carousel|house/, 'place'],
  [/robot|spaceship|satellite|radio|car|bicycle|compass|arcade|portal|brain|hourglass|plasma|crystal/, 'tech'],
];

export function familyOf(file) {
  const name = file.toLowerCase();
  for (let index = 0; index < FAMILY_RULES.length; index += 1) {
    if (FAMILY_RULES[index][0].test(name)) return FAMILY_RULES[index][1];
  }
  return 'object';
}
